"""Run a FrontierCS 2.0 task through tide (requires Docker + the harbor extra).

A ready-made task (erdos_demo, generated by FrontierCS's official Harbor
adapter) is vendored in tasks/frontier-cs/. To generate more:

    git clone https://github.com/FrontierCS/Frontier-CS && cd Frontier-CS
    PYTHONPATH=adapters/frontier-cs-2.0/src python -m frontier_cs_2_0.main \\
        --source . --output-dir <out> --task-ids erdos_unit_distance

    python examples/run_frontiercs.py                          # oracle on the pinned task
    python examples/run_frontiercs.py --agent claude-code --model anthropic/claude-opus-5
"""

import argparse
import asyncio
from pathlib import Path

from tide import Lab

TASK = str(
    Path(__file__).parent.parent
    / "tasks"
    / "frontier-cs"
    / "frontier-cs-2-0-erdos-demo"
)


async def main(agent: str, model: str | None):
    lab = Lab("runs/frontiercs")
    cfg = {"name": agent, **({"model_name": model} if model else {})}
    row = await lab.run(TASK, cfg, tags={"benchmark": "frontier-cs-2.0"})
    print(f"{agent}:", row.rewards)
    print("trial:", row.uri)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--agent", default="oracle")
    parser.add_argument("--model", default=None)
    args = parser.parse_args()
    asyncio.run(main(args.agent, args.model))
